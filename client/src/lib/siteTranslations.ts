const reverseTranslations = Object.fromEntries(Object.entries(translations).map(([arabic, english]) => [english, arabic]));

export function translateSiteText(value: string, language: "ar" | "en") {
  if (language === "ar") return replaceKnown(value, reverseTranslations);
  return replaceKnown(value, translations);
}

function replaceKnown(value: string, dictionary: Record<string, string>) {
  const keys = Object.keys(dictionary).sort((a, b) => b.length - a.length);
  let result = value;
  for (const key of keys) {
    if (result.includes(key)) result = result.split(key).join(dictionary[key]);
  }
  return result;
}
